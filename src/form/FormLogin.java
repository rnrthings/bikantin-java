    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed

    String username = txtUsername.getText();
    String password = new String(txtPassword.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(
            this, "Username dan password wajib diisi!"
        );
        return;
    }

    try {
        Connection conn = Koneksi.configDB();

        if (conn == null) {
            JOptionPane.showMessageDialog(
                this, "Koneksi database gagal!"
            );
            return;
        }

        String sql = "SELECT * FROM users "
                + "WHERE username = ? AND password = ?";

        java.sql.PreparedStatement pst = conn.prepareStatement(sql);

        pst.setString(1, username);
        pst.setString(2, password);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            String role = rs.getString("role");
            int idUser = rs.getInt("id");

            rs.close();
            pst.close();
            conn.close();

            if (role.equalsIgnoreCase("admin")) {

                new FormAdmin().setVisible(true);
                this.dispose();

            } else if (role.equalsIgnoreCase("siswa")) {

                new FormSiswa(idUser, username).setVisible(true);
                this.dispose();

            } else {

                JOptionPane.showMessageDialog(
                    this, "Role pengguna tidak dikenali!"
                );

            }

        } else {

            rs.close();
            pst.close();
            conn.close();

            JOptionPane.showMessageDialog(
                this, "Username atau password salah!"
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this, "Terjadi kesalahan: " + e.getMessage()
        );

    }

    }//GEN-LAST:event_btnLoginActionPerformed

